type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, params?: Params) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(message: string, params?: Params): string {
  if (!params) return message;
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

function initialLocale(): Locale {
  const saved = localStorage.getItem("tatami-locale");
  if (saved === "en" || saved === "uk") return saved;
  return "uk";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, updateLocale] = useState<Locale>(initialLocale);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const setLocale = (next: Locale) => {
    localStorage.setItem("tatami-locale", next);
    document.documentElement.lang = next;
    updateLocale(next);
  };
  const t = (key: string, params?: Params) => interpolate((locale === "uk" ? uk[key] : undefined) ?? en[key] ?? key, params);
  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useI18n();
  return (
    <div className="language-switcher" role="group" aria-label={t("common.language")}>
      <button type="button" className={locale === "uk" ? "is-active" : ""} onClick={() => setLocale("uk")}>{t("language.uk")}</button>
      <button type="button" className={locale === "en" ? "is-active" : ""} onClick={() => setLocale("en")}>{t("language.en")}</button>
    </div>
  );
}
